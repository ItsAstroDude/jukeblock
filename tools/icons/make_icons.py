"""
Generates the transport icon sheet for Jukeblock.

The icons are hand-authored pixel art rather than drawn shapes: Minecraft's UI is
pixel art, and at GUI scale 4 every pixel is four screen pixels, so anything
anti-aliased or off-grid reads as mush. Each glyph is 16x16, pure white with an
alpha channel, so the panel can tint it per state (accent when active, grey when
the source doesn't support it).

    python tools/icons/make_icons.py

Writes src/main/resources/assets/jukeblock/textures/gui/icons.png, plus a
magnified preview next to this script for eyeballing changes.
"""

